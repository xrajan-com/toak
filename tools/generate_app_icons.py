#!/usr/bin/env python3
"""Generates every app icon from one master image.

Master: design_sources/brand/app-icon-master.png (square, at least 1024 px,
full-bleed artwork with no rounded corners; each platform applies its own
shape). Replace the master and run this script; never edit the outputs by hand.

    python3 tools/generate_app_icons.py      # needs: pip3 install pillow numpy

Writes:
  fastlane/metadata/android/en-US/images/icon.png      Play listing icon, 512 px
  android/app/src/main/res/mipmap-*/ic_launcher.png     legacy launcher, rounded square
  android/app/src/main/res/mipmap-*/ic_launcher_round.png
  android/app/src/main/res/mipmap-*/ic_launcher_background.png   adaptive icon layer
  android/app/src/main/res/mipmap-*/ic_launcher_foreground.png   adaptive icon layer (empty)
  android/app/src/main/res/mipmap-anydpi-v26/ic_launcher*.xml
  ios/Runner/Assets.xcassets/AppIcon.appiconset/*.png  every size Contents.json lists

Adaptive icons are 108 dp layers of which launchers show the central 72 dp.
The artwork fills exactly that 72 dp window; the 18 dp margins around it are
the artwork's own edges, mirrored and blurred, so launcher parallax and
animations never reveal a hard edge. The web favicon is deliberately not
generated here.
"""
import json
import pathlib
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = pathlib.Path(__file__).resolve().parent.parent
MASTER = ROOT / 'design_sources/brand/app-icon-master.png'
RES = ROOT / 'android/app/src/main/res'
IOS = ROOT / 'ios/Runner/Assets.xcassets/AppIcon.appiconset'
PLAY = ROOT / 'fastlane/metadata/android/en-US/images/icon.png'
DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}

ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_app_icons.py from design_sources/brand/app-icon-master.png -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""


def load_master():
    if not MASTER.exists():
        sys.exit(f'ERROR: master icon not found: {MASTER.relative_to(ROOT)}')
    im = Image.open(MASTER).convert('RGB')
    w, h = im.size
    if w != h or w < 1024:
        sys.exit(f'ERROR: master icon must be square and at least 1024 px, got {w}x{h}')
    return im


def sized(im, px):
    return im.resize((px, px), Image.LANCZOS)


def shaped(im, px, shape):
    big = px * 4
    m = Image.new('L', (big, big), 0)
    d = ImageDraw.Draw(m)
    if shape == 'circle':
        d.ellipse([0, 0, big - 1, big - 1], fill=255)
    else:
        d.rounded_rectangle([0, 0, big - 1, big - 1], radius=int(big * 0.18), fill=255)
    out = sized(im, px).convert('RGBA')
    out.putalpha(m.resize((px, px), Image.LANCZOS))
    return out


def adaptive_background(im, px):
    pad = round(px * 18 / 108)
    inner = px - 2 * pad
    art = np.asarray(sized(im, inner)).astype(np.float32)
    padded = np.pad(art, ((pad, pad), (pad, pad), (0, 0)), mode='reflect')
    blurred = np.asarray(
        Image.fromarray(padded.astype(np.uint8)).filter(ImageFilter.GaussianBlur(px / 36))
    ).astype(np.float32)
    keep = np.zeros((px, px, 1), np.float32)
    keep[pad:pad + inner, pad:pad + inner] = 1.0
    out = padded * keep + blurred * (1.0 - keep)
    return Image.fromarray(np.clip(out, 0, 255).astype(np.uint8), 'RGB')


def main():
    im = load_master()
    written = []

    PLAY.parent.mkdir(parents=True, exist_ok=True)
    sized(im, 512).convert('RGBA').save(PLAY, optimize=True)   # Play wants a 32-bit PNG
    written.append(PLAY)

    for density, scale in DENSITIES.items():
        folder = RES / f'mipmap-{density}'
        folder.mkdir(parents=True, exist_ok=True)
        legacy, layer = round(48 * scale), round(108 * scale)
        shaped(im, legacy, 'rounded').save(folder / 'ic_launcher.png', optimize=True)
        shaped(im, legacy, 'circle').save(folder / 'ic_launcher_round.png', optimize=True)
        adaptive_background(im, layer).save(folder / 'ic_launcher_background.png', optimize=True)
        Image.new('RGBA', (layer, layer), (0, 0, 0, 0)).save(folder / 'ic_launcher_foreground.png', optimize=True)
        written += [folder / n for n in ('ic_launcher.png', 'ic_launcher_round.png',
                                         'ic_launcher_background.png', 'ic_launcher_foreground.png')]

    anydpi = RES / 'mipmap-anydpi-v26'
    anydpi.mkdir(parents=True, exist_ok=True)
    for name in ('ic_launcher.xml', 'ic_launcher_round.xml'):
        (anydpi / name).write_text(ADAPTIVE_XML)
        written.append(anydpi / name)

    contents = json.loads((IOS / 'Contents.json').read_text())
    for entry in contents['images']:
        points = float(entry['size'].split('x')[0])
        px = round(points * int(entry['scale'].rstrip('x')))
        sized(im, px).save(IOS / entry['filename'], optimize=True)   # iOS icons must be opaque
        written.append(IOS / entry['filename'])

    print(f'Generated {len(written)} icon files from {MASTER.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
