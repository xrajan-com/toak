// Builds the kingdom scenes into the app:
//   assets/scenes/<id>.json      one recorded scene each
//   assets/scenes/icons.json     the icon paths those scenes use (+ authors)
//   lib/config/kingdom_scenes.g.dart   kingdom -> scenes catalogue (with each scene's ambience bed, ambience_beds.js)
// Usage (from the repo root): node tools/scenes/build.js [kingdom ...]
const fs = require('fs'), path = require('path'), vm = require('vm');
const here = __dirname, repo = path.resolve(here, '../..');
const { Rec, RecPath, encodePath } = require('./engine/rec.js');
const { normalizeSvgPath } = require('./engine/svgpath.js');
const { BEDS, bedFor } = require('./ambience_beds.js');

const ctx = vm.createContext({ Path2D: RecPath, console, Math, JSON, module: undefined });
ctx.globalThis = ctx;
for (const f of ['engine/icons.js', 'kit.js', 'kit2.js', ...fs.readdirSync(here).filter((f) => /^t_.*\.js$/.test(f)).sort(), 'kingdoms.js'])
  vm.runInContext(fs.readFileSync(path.join(here, f), 'utf8'), ctx, { filename: f });
const { KINGDOMS, TEMPLATES, ICONS, ICON_AUTHORS } = vm.runInContext('({ KINGDOMS, TEMPLATES, ICONS, ICON_AUTHORS })', ctx);

const SLOTS = ['history', 'animals', 'bar', 'rock', 'sport', 'wild-1', 'wild-2'];
const KIND = { history: 'history', animals: 'animals', bar: 'bar', rock: 'rock', sport: 'sport', 'wild-1': 'wild', 'wild-2': 'wild' };
const slug = (s) => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
function hashStr(s) { let h = 2166136261; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; }
function rngFor(seed) { let s = seed >>> 0; return () => ((s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 4294967296); }

const only = process.argv.slice(2);
const outDir = path.join(repo, 'assets/scenes');
fs.mkdirSync(outDir, { recursive: true });
const usedIcons = new Set(), catalogue = [];
let bytes = 0, count = 0;
for (const [kingdom, scenes] of Object.entries(KINGDOMS)) {
  if (scenes.length !== 7) throw new Error(`${kingdom}: needs 7 scenes, has ${scenes.length}`);
  const entries = [];
  scenes.forEach(([kind, template, title, opts], i) => {
    const slot = SLOTS[i];
    if (KIND[slot] !== kind) throw new Error(`${kingdom}: scene ${i + 1} should be ${KIND[slot]}, is ${kind}`);
    if (!TEMPLATES[template]) throw new Error(`${kingdom}: unknown template ${template}`);
    const id = `${slug(kingdom)}-${slot}`;
    const bed = bedFor(kind, template, opts);
    if (!BEDS.includes(bed)) throw new Error(`${id}: unknown ambience bed ${bed}`);
    entries.push({ id, kind, title, bed });
    if (only.length && !only.includes(kingdom)) return;
    const rec = new Rec();
    TEMPLATES[template](rec, rngFor(hashStr(id)), opts || {});
    const scene = rec.finish({ id });
    for (const op of scene.ops) if (op[0] === 'I') usedIcons.add(op[1]);
    const json = JSON.stringify(scene);
    fs.writeFileSync(path.join(outDir, id + '.json'), json);
    bytes += json.length; count++;
  });
  catalogue.push([kingdom, entries]);
}
// Icons: every icon any scene on disk uses (scan all files so partial builds stay complete).
for (const f of fs.readdirSync(outDir)) if (f.endsWith('.json') && f !== 'icons.json') for (const op of JSON.parse(fs.readFileSync(path.join(outDir, f), 'utf8')).ops) if (op[0] === 'I') usedIcons.add(op[1]);
const icons = {}, authors = {};
for (const name of [...usedIcons].sort()) {
  if (!ICONS[name]) throw new Error('icon missing from engine/icons.js: ' + name);
  const p = new RecPath();
  for (const m of ICONS[name].matchAll(/([MLQCZ])([^MLQCZ]*)/g)) {
    const v = m[2].trim() ? m[2].trim().split(/[\s,]+/).map(Number) : [];
    if (m[1] === 'M') p.moveTo(v[0], v[1]); else if (m[1] === 'L') p.lineTo(v[0], v[1]); else if (m[1] === 'Q') p.quadraticCurveTo(...v); else if (m[1] === 'C') p.bezierCurveTo(...v); else p.closePath();
  }
  icons[name] = encodePath(p.cmds); authors[name] = ICON_AUTHORS[name];
}
fs.writeFileSync(path.join(outDir, 'icons.json'), JSON.stringify({ source: 'game-icons.net, CC BY 3.0', authors, icons }));
// Catalogue for the app.
const dq = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
let dart = '// GENERATED by tools/scenes/build.js from tools/scenes/kingdoms.js.\n// Do not edit by hand: change kingdoms.js and run the build.\n\npart of \'kingdom_scenes.dart\';\n\nconst Map<String, List<KingdomScene>> _kKingdomScenes = <String, List<KingdomScene>>{\n';
for (const [k, entries] of catalogue) {
  dart += `  ${dq(k)}: <KingdomScene>[\n`;
  for (const e of entries) dart += `    KingdomScene(${dq(e.id)}, SceneKind.${e.kind}, ${dq(e.title)}, AmbienceBed.${e.bed}),\n`;
  dart += '  ],\n';
}
dart += '};\n';
fs.writeFileSync(path.join(repo, 'lib/config/kingdom_scenes.g.dart'), dart);
console.log(`${count} scenes, ${(bytes / 1024).toFixed(0)} KB, ${usedIcons.size} icons, ${catalogue.length} kingdoms in the catalogue`);
