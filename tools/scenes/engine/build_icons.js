// node build_icons.js <game-icons root> <out dir> name|author/name ...
const fs = require('fs'), path = require('path');
const { normalizeSvgPath } = require('./svgpath.js');
const [root, outDir, ...names] = process.argv.slice(2);
const idx = {};
for (const a of fs.readdirSync(root)) { const p = path.join(root, a); if (fs.statSync(p).isDirectory()) for (const f of fs.readdirSync(p)) if (f.endsWith('.svg')) (idx[f.slice(0, -4)] ||= []).push(a); }
const icons = {}, raw = {}, credit = {};
for (const n of names) {
  const [author, base] = n.includes('/') ? n.split('/') : [null, n];
  const a = author || (idx[base] || [])[0];
  if (!a) { console.error('missing icon', n); process.exitCode = 1; continue; }
  const svg = fs.readFileSync(path.join(root, a, base + '.svg'), 'utf8');
  const ds = [...svg.matchAll(/<path[^>]*?\sd="([^"]+)"/g)].map((m) => m[1]).filter((d) => d.trim() !== 'M0 0h512v512H0z');
  raw[base] = ds.join(' ');
  icons[base] = normalizeSvgPath(raw[base]);
  credit[base] = a;
}
// icons.js: game-icons.net silhouettes (CC BY 3.0; authors listed), as
// absolute M/L/Q/C/Z paths in a 512 box. Regenerate with build_icons.js.
fs.writeFileSync(path.join(outDir, 'icons.js'), '// Generated by build_icons.js from game-icons.net (CC BY 3.0, authors in ICON_AUTHORS).\nvar ICONS=' + JSON.stringify(icons, null, 0) + ';\nvar ICON_AUTHORS=' + JSON.stringify(credit) + ';\nif(typeof module!=="undefined")module.exports={ICONS,ICON_AUTHORS};\n');
console.log(Object.keys(icons).length, 'icons,', JSON.stringify(icons).length, 'bytes');
